#!/usr/bin/env python3
"""Inject the port status and the OCaml signature into the generated docs.

Why this exists: the per-component reference text (docs/components/<Name>.md) is
generated from upstream's machine-readable docs, so on its own it describes the
*React* component. An agent reading it would not know whether an OCaml port
exists, what module to reach for, or what the OCaml call looks like. This script
closes that gap using two machine-readable sources — port.json (what has been
ported) and the .mli files (the actual signatures) — so the answer cannot drift
from the code.

Regenerate:  python3 tools/gen-port-status.py
Idempotent: the injected block is delimited by markers and replaced wholesale.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
COMPONENTS = DOCS / "components"

BEGIN = "<!-- port-status:begin (generated by tools/gen-port-status.py) -->"
END = "<!-- port-status:end -->"


def read_port_json() -> dict:
    return json.loads((ROOT / "port.json").read_text())


def upstream_components() -> list[str]:
    registry = json.loads((ROOT / "registry.json").read_text())
    if isinstance(registry, dict):
        for key in ("components", "items"):
            if key in registry:
                entries = registry[key]
                break
        else:
            raise SystemExit("registry.json has no 'components' list")
    else:
        entries = registry
    names = []
    for entry in entries:
        name = entry.get("name") or entry.get("component")
        if name:
            names.append(name)
    return names


def module_signature(ml_file: Path) -> str:
    """Pull the `val view ...` declaration out of an .mli file.

    The port keeps one entry point per component named `view`, so a simple
    line-based scan is enough and — unlike a hand-written summary — cannot
    disagree with what the compiler sees.
    """
    mli = ml_file.with_suffix(".mli")
    if not mli.exists():
        return ""
    lines = mli.read_text().splitlines()
    start = None
    for i, line in enumerate(lines):
        if re.match(r"^val view\b", line):
            start = i
            break
    if start is None:
        return ""
    out = []
    for line in lines[start:]:
        if out and line.strip() and not line.startswith((" ", "\t")) and not line.startswith("val"):
            break
        out.append(line.rstrip())
        if line.rstrip().endswith("-> Vdom.Node.t") or line.rstrip().endswith("Vdom.Node.t"):
            break
    return "\n".join(out).rstrip()


def ported_index(port: dict) -> dict[str, dict]:
    return {entry["component"]: entry for entry in port["ported"]}


def status_block(name: str, entry: dict | None, port: dict) -> str:
    if entry is None:
        return (
            f"{BEGIN}\n## OCaml port\n\n"
            f"**Status:** not ported yet. The upstream contract above is the specification; "
            f"see `docs/PORT-STATUS.md` for the milestone it is planned in.\n\n"
            f"{END}\n"
        )
    ml_file = ROOT / entry["file"]
    sig = module_signature(ml_file)
    lines = [
        BEGIN,
        "## OCaml port",
        "",
        f"**Status:** ported in {entry['milestone']} — [`{entry['file']}`](../{entry['file']})",
        "",
        f"**Module:** `{entry['module']}` (open `Astryx`)",
        "",
    ]
    if sig:
        lines += ["```ocaml", sig, "```", ""]
    lines += [
        "Call it with the same prop names and defaults the upstream contract above "
        "documents; `Divergence` comments in the source record the few places the "
        "port deliberately differs (class names, and inline styles for per-instance "
        "numeric props).",
        "",
        END,
        "",
    ]
    return "\n".join(lines)


def inject(path: Path, block: str) -> bool:
    """Replace or append the generated block. Returns True if the file changed."""
    text = path.read_text()
    if BEGIN in text and END in text:
        start = text.index(BEGIN)
        end = text.index(END) + len(END)
        new = text[:start] + block.rstrip("\n") + text[end:]
    else:
        new = text.rstrip("\n") + "\n\n" + block
    if new == text:
        return False
    path.write_text(new)
    return True


def write_status_page(port: dict, components: list[str], ported: dict[str, dict]) -> None:
    lines = [
        "<!-- generated by tools/gen-port-status.py — do not edit by hand -->",
        "",
        "# Port status",
        "",
        f"Upstream: `{port['upstream']['repo']}` @ `{port['upstream']['commit']}`",
        "",
        f"Ported: **{len(ported)} of {len(components)}** components.",
        "",
        "## Milestones",
        "",
    ]
    for m in port["milestones"]:
        lines.append(f"- **{m['id']} — {m['name']}**: {m['status']}. {m['note']}")
    lines += [
        "",
        "## Infrastructure",
        "",
        "| Module | File | What it holds |",
        "| --- | --- | --- |",
    ]
    for item in port["infrastructure"]:
        lines.append(f"| `{item['module']}` | `{item['file']}` | {item['note']} |")
    lines += [
        "",
        "## Ported components",
        "",
        "| Component | Module | File | Milestone | Upstream class |",
        "| --- | --- | --- | --- | --- |",
    ]
    for entry in port["ported"]:
        lines.append(
            f"| `{entry['component']}` | `{entry['module']}` | `{entry['file']}` | "
            f"{entry['milestone']} | {entry['class']} |"
        )
    pending = [c for c in components if c not in ported]
    lines += [
        "",
        f"## Not ported yet ({len(pending)})",
        "",
        "Listed in the order the inventory reports them. Each one has reference text "
        "in `docs/components/` describing the upstream contract it will have to match.",
        "",
    ]
    lines.append(", ".join(f"`{c}`" for c in pending) if pending else "_(none)_")
    lines.append("")
    (DOCS / "PORT-STATUS.md").write_text("\n".join(lines))


def main() -> None:
    port = read_port_json()
    ported = ported_index(port)
    components = upstream_components()

    missing = sorted(set(ported) - set(components))
    if missing:
        raise SystemExit(
            "port.json names components that are not in registry.json: " + ", ".join(missing)
        )

    changed = 0
    for name in components:
        path = COMPONENTS / f"{name}.md"
        if not path.exists():
            continue
        if inject(path, status_block(name, ported.get(name), port)):
            changed += 1

    write_status_page(port, components, ported)
    print(f"docs updated: {changed} component page(s) touched")
    print(f"ported {len(ported)}/{len(components)}; wrote docs/PORT-STATUS.md")


if __name__ == "__main__":
    main()
